// Generates packages/sources/fixtures/index.ts (ARCHITECTURE §5.3): one static JSON import per fixture,
// so the bundler embeds them and replay never reads the disk at runtime.
// Usage: node scripts/generate-fixtures-index.ts
import { execFileSync } from 'node:child_process';
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

export const FIXTURES_DIR = 'packages/sources/fixtures';
const INDEX = join(FIXTURES_DIR, 'index.ts');

export function listFixtureFiles(dir = FIXTURES_DIR): string[] {
  const out: string[] = [];
  const walk = (d: string): void => {
    for (const name of readdirSync(d).sort()) {
      const path = join(d, name);
      if (statSync(path).isDirectory()) walk(path);
      else if (name.endsWith('.json')) out.push(path);
    }
  };
  walk(dir);
  return out.sort();
}

export function renderIndex(files: readonly string[], dir = FIXTURES_DIR): string {
  const imports = files.map(
    (f, i) =>
      `import f${i} from './${relative(dir, f).split('\\').join('/')}' with { type: 'json' };`,
  );
  const names = files.map((_, i) => `f${i}`).join(', ');
  return [
    '// Generated by `pnpm fixtures:index` (scripts/generate-fixtures-index.ts). Do not edit by hand.',
    '// Static JSON imports: the bundler embeds every fixture, no fs at runtime (ARCHITECTURE §5.3).',
    ...(imports.length > 0 ? ['', ...imports] : []),
    '',
    `export const FIXTURES: readonly unknown[] = [${names}];`,
    '',
  ].join('\n');
}

/** Formats files with the repository's Biome config (fixtures are JSON checked by `pnpm lint`). */
export function biomeFormat(paths: readonly string[]): void {
  if (paths.length === 0) return;
  execFileSync('pnpm', ['exec', 'biome', 'format', '--write', ...paths], { stdio: 'ignore' });
}

export function generateIndex(): string {
  const files = listFixtureFiles();
  writeFileSync(INDEX, renderIndex(files));
  biomeFormat([INDEX]);
  return INDEX;
}

if (import.meta.main) {
  const path = generateIndex();
  console.log(`fixtures:index: ${path} (${listFixtureFiles().length} fixture(s))`);
}
